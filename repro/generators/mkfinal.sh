#!/bin/bash
# usage: OUTDIR=DIR mkfinal.sh NAME p1 p2 ...    writes DIR/NAME.lean (DIR = lean/LRSpectrumFull/NineSound) importing G<p>.PD for the listed primes.
# If the list is exactly the 36 primes of S36 (in S36 order) the module is the final one (theorem nine_runners_final, hypotheses: LRC7 only);
# otherwise it is a partial assembly (theorem nine_runners_partial: LRC7 and PrimeData p for the primes of S36 outside the list).
L=${OUTDIR:?set OUTDIR to the directory that receives NAME.lean}
S36="53 61 67 71 79 83 89 97 101 103 107 109 113 127 131 137 139 149 151 157 163 167 173 179 181 191 193 197 199 211 223 227 229 233 239 241"
NAME=$1; shift
PL="$*"
F=$L/$NAME.lean
{
  echo "/- GENERATED by repro/generators/mkfinal.sh: assembly module for the primes: $PL (not part of any aggregator) -/"
  echo "import LRSpectrumFull.NineSound.Final9"
  [ "$SHAPE" = 1 ] || for p in $PL; do echo "import LRSpectrumFull.NineSound.G$p.PD"; done
  echo ""
  echo "namespace LRSpectrumFull.NineSound.Plan9.$NAME"
  echo "open LRSpectrumFull LRSpectrumFull.NineSound"
  echo ""
  if [ "$PL" = "$S36" ]; then
    BIND=""; [ "$SHAPE" = 1 ] && for p in $PL; do BIND="$BIND (s$p : PrimeData $p)"; done
    echo "theorem pd36$BIND : ∀ p ∈ S36, PrimeData p := by"
    echo "  intro p hp"
    echo "  have h := mem_S36.mp hp"
    echo "  simp only [S36L, List.mem_cons, List.not_mem_nil, or_false] at h"
    printf '  rcases h with rfl'
    n=0; for p in $PL; do n=$((n+1)); [ $n -gt 1 ] && printf ' | rfl'; done
    echo ""
    for p in $PL; do if [ "$SHAPE" = 1 ]; then echo "  · exact s$p"; else echo "  · exact LRSpectrumFull.NineSound.G$p.PD.primeData_$p"; fi; done
    echo ""
    if [ "$SHAPE" != 1 ]; then
    echo "/-- **Nine runners (all 36 primes closed by generated modules).**  The only hypothesis is \`LRC7\`. -/"
    echo "theorem nine_runners_final (h7 : LRC7) (v : Fin 8 → ℤ) (hv : ∀ i, 0 < v i) : 1 / 9 ≤ ML v :="
    echo "  nine_runners_of_data h7 pd36 v hv"
    fi
  else
    SET=$(echo $PL | sed 's/ /, /g')
    echo "theorem hk : ∀ p ∈ ({$SET} : Finset ℕ), PrimeData p := by"
    echo "  intro p hp"
    echo "  simp only [Finset.mem_insert, Finset.mem_singleton] at hp"
    printf '  rcases hp with rfl'
    n=0; for p in $PL; do n=$((n+1)); [ $n -gt 1 ] && printf ' | rfl'; done
    echo ""
    for p in $PL; do echo "  · exact LRSpectrumFull.NineSound.G$p.PD.primeData_$p"; done
    echo ""
    echo "/-- **Nine runners, partial assembly.**  Hypotheses: \`LRC7\` and \`PrimeData p\` for the primes of \`S36\` outside {$SET}. -/"
    echo "theorem nine_runners_partial (h7 : LRC7) (hr : ∀ p ∈ S36, p ∉ ({$SET} : Finset ℕ) → PrimeData p)"
    echo "    (v : Fin 8 → ℤ) (hv : ∀ i, 0 < v i) : 1 / 9 ≤ ML v :="
    echo "  nine_runners_of_closed h7 _ hk hr v hv"
  fi
  echo ""
  echo "end LRSpectrumFull.NineSound.Plan9.$NAME"
  if [ "$PL" = "$S36" ] && [ "$SHAPE" != 1 ]; then
    echo ""
    echo "#print axioms LRSpectrumFull.NineSound.Plan9.$NAME.pd36"
    echo "#print axioms LRSpectrumFull.NineSound.Plan9.$NAME.nine_runners_final"
    echo "#check @LRSpectrumFull.NineSound.Plan9.$NAME.nine_runners_final"
  fi
} > $F
echo "wrote $F ($(wc -l < $F) lines)"
